"""
Задача 1.3. Рассылка без дублей

Ситуация: перед рассылкой нужно собрать список адресов из выгрузки пользователей.
В выгрузке есть дубли с разным регистром и пробелами, пустые значения и None.

Что сделать: вернуть уникальные адреса в нижнем регистре, без пробелов по краям,
в порядке первого появления. Пустые и None пропустить. Список может быть на
сотни тысяч записей - решение должно работать за O(n).

На собесе: "Как убрать дубли из списка, сохранив порядок? Почему проверка
'x in list' в цикле - плохая идея?"
"""


def unique_emails(users):
    unique = {user["email"].strip().lower(): None for user in users if user["email"] and user["email"].strip()}
    return list(unique)
