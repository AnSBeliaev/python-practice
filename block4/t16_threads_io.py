"""
Задача 4.1. Проверка ссылок в документах

Ситуация: перед загрузкой документа сервис проверяет все внешние ссылки в нём.
Ссылок бывает 50-100, каждая проверяется ~0.2-1 сек, и загрузка висит минуту.
Почти всё это время программа просто ждёт ответа сети.

Что сделать: переписать check_links на потоках (concurrent.futures,
ThreadPoolExecutor, до max_workers потоков).
- результат в том же порядке, что и urls
- если check(url) упал с исключением, на его месте - само исключение,
  остальные ссылки всё равно проверяются

На собесе: "Что такое GIL? Почему потоки ускоряют работу с сетью, если из-за
GIL Python-код выполняется в один поток?"
"""


def check_links(urls, check, max_workers=10):
    results = []
    for url in urls:
        try:
            results.append(check(url))
        except Exception as error:
            results.append(error)
    return results
