"""
Задача 4.6. Минусовой баланс

Ситуация: списание бонусов с баланса пользователя. Проверка "хватает ли
бонусов" есть, но под нагрузкой (много запросов одновременно) баланс уходит
в минус. Задержка внутри withdraw имитирует запрос к базе.

Что сделать:
1) Запустить тест и убедиться, что он падает. Объяснить, почему так
   происходит, хотя проверка баланса есть.
2) Исправить Account так, чтобы баланс никогда не уходил в минус при
   одновременных списаниях (threading.Lock). Задержку не удалять.

На собесе: "Что такое состояние гонки? Защищает ли GIL от гонок? Как такая же
проблема решается в базе данных (SELECT ... FOR UPDATE)?"
"""

import time


class Account:
    def __init__(self, balance):
        self.balance = balance

    def withdraw(self, amount):
        if self.balance >= amount:
            time.sleep(0.001)
            self.balance -= amount
            return True
        return False
